import { z } from "zod";

const schema = z.object({
  MONGODB_URI: z.string().min(1, "MONGODB_URI is required"),
  AUTH_SECRET: z.string().min(32, "AUTH_SECRET must be at least 32 characters"),
  GEMINI_API_KEY: z.string().optional(),
  GEMINI_IMAGE_MODEL: z.string().default("gemini-2.5-flash-image"),
  // Payments (Stripe Checkout). PAYMENT_SECRET = Stripe secret key, PAYMENT_WEBHOOK_SECRET = webhook signing secret.
  PAYMENT_PROVIDER: z.enum(["stripe"]).default("stripe"),
  PAYMENT_SECRET: z.string().optional(),
  PAYMENT_WEBHOOK_SECRET: z.string().optional(),
  // Image storage: local disk (public/generated by default)
  LOCAL_STORAGE_DIR: z.string().default("public/generated"),
  // Email (password reset). Without a key, links are logged to the server console in development.
  RESEND_API_KEY: z.string().optional(),
  EMAIL_FROM: z.string().default("TattooGenerator <noreply@tattoogenerator.com>"),
  NEXT_PUBLIC_APP_URL: z.string().default("http://localhost:3000"),
});

export type Env = z.infer<typeof schema>;

let cached: Env | undefined;

/** Validated env, parsed lazily so `next build` works without secrets. */
export function env(): Env {
  if (cached) return cached;
  const parsed = schema.safeParse(process.env);
  if (!parsed.success) {
    // Log the field names only, never values.
    console.error("Invalid environment:", parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`));
    throw new Error("Server is not configured correctly.");
  }
  cached = parsed.data;
  return cached;
}
